"""Proximal Policy Optimization (clipped objective) with GAE, trained on several tasks at once.

Each update collects a fresh on-policy rollout for every task with the current
policy, computes generalized advantage estimates within that rollout, and then
optimizes the summed per-task PPO losses for a few epochs of minibatches. No
replay buffer is used: PPO's ratio ``pi_new / pi_old`` is only valid for data
generated by ``pi_old``.
"""

from __future__ import annotations

import time
from dataclasses import asdict, dataclass, field

import numpy as np
import torch
from torch import nn
from torch.distributions import Categorical

from .envs import GridTask, make
from .network import MultiTaskActorCritic


@dataclass
class PPOConfig:
    tasks: tuple[str, ...] = ("navigation", "key_door")
    size: int = 7
    num_envs: int = 32
    rollout_steps: int = 128
    updates: int = 600
    epochs: int = 4
    minibatches: int = 4
    learning_rate: float = 7e-4
    gamma: float = 0.99
    gae_lambda: float = 0.95
    clip: float = 0.2
    value_coef: float = 0.5
    entropy_coef: float = 0.01
    entropy_coef_final: float = 0.0003  # linearly annealed so the policy becomes decisive late in training
    max_grad_norm: float = 0.5
    shaping: float = 0.05
    bootstrap_truncation: bool = True
    seed: int = 7


def gae(rewards: np.ndarray, values: np.ndarray, dones: np.ndarray, last_value: np.ndarray, gamma: float, lam: float) -> tuple[np.ndarray, np.ndarray]:
    """Generalized advantage estimation over a ``(steps, envs)`` rollout.

    ``dones[t]`` marks that the episode ended after step ``t``; the value of the
    next state is then ignored and the recursion restarts.
    """
    steps = rewards.shape[0]
    advantages = np.zeros_like(rewards)
    running = np.zeros(rewards.shape[1], dtype=np.float32)
    for t in reversed(range(steps)):
        next_value = last_value if t == steps - 1 else values[t + 1]
        not_done = 1.0 - dones[t]
        delta = rewards[t] + gamma * next_value * not_done - values[t]
        running = delta + gamma * lam * not_done * running
        advantages[t] = running
    return advantages, advantages + values


def clipped_policy_loss(new_log_prob: torch.Tensor, old_log_prob: torch.Tensor, advantages: torch.Tensor, clip: float) -> torch.Tensor:
    ratio = torch.exp(new_log_prob - old_log_prob)
    return -torch.min(ratio * advantages, torch.clamp(ratio, 1 - clip, 1 + clip) * advantages).mean()


@dataclass
class UpdateStats:
    update: int
    env_steps: int
    seconds: float
    per_task: dict = field(default_factory=dict)


class TaskRollout:
    """A set of environments for one task, stepping in lockstep."""

    def __init__(self, task: str, config: PPOConfig, seed: int):
        self.task = task
        self.envs: list[GridTask] = [make(task, size=config.size, seed=seed + i, shaping=config.shaping, gamma=config.gamma) for i in range(config.num_envs)]
        self.observations = np.stack([env.reset() for env in self.envs])
        self.episode_returns = np.zeros(config.num_envs, dtype=np.float32)
        self.finished: list[tuple[float, bool]] = []

    def collect(self, model: MultiTaskActorCritic, steps: int, gamma: float = 0.99, bootstrap: bool = True) -> dict:
        n = len(self.envs)
        buffers = {
            "obs": np.zeros((steps, n, *self.observations.shape[1:]), dtype=np.float32),
            "actions": np.zeros((steps, n), dtype=np.int64),
            "log_probs": np.zeros((steps, n), dtype=np.float32),
            "values": np.zeros((steps, n), dtype=np.float32),
            "rewards": np.zeros((steps, n), dtype=np.float32),
            "dones": np.zeros((steps, n), dtype=np.float32),
        }
        for t in range(steps):
            with torch.no_grad():
                logits, value = model(torch.from_numpy(self.observations), self.task)
                dist = Categorical(logits=logits)
                action = dist.sample()
            buffers["obs"][t] = self.observations
            buffers["actions"][t] = action.numpy()
            buffers["log_probs"][t] = dist.log_prob(action).numpy()
            buffers["values"][t] = value.numpy()
            for i, env in enumerate(self.envs):
                result = env.step(int(action[i]))
                buffers["rewards"][t, i] = result.reward
                self.episode_returns[i] += result.info.get("task_reward", result.reward)
                if bootstrap and result.truncated and not result.terminated:
                    # A time limit is not a real ending: bootstrap from the value of the
                    # state the agent was cut off in, so the critic is not taught that
                    # the step limit is a terminal state.
                    with torch.no_grad():
                        _, cut_value = model(torch.from_numpy(result.observation).unsqueeze(0), self.task)
                    buffers["rewards"][t, i] += gamma * float(cut_value)
                if result.terminated or result.truncated:
                    buffers["dones"][t, i] = 1.0
                    self.finished.append((float(self.episode_returns[i]), bool(result.info.get("success"))))
                    self.episode_returns[i] = 0.0
                    self.observations[i] = env.reset()
                else:
                    self.observations[i] = result.observation
        with torch.no_grad():
            _, last_value = model(torch.from_numpy(self.observations), self.task)
        buffers["last_value"] = last_value.numpy()
        return buffers

    def drain_episodes(self) -> list[tuple[float, bool]]:
        done, self.finished = self.finished, []
        return done


def train(config: PPOConfig, *, on_update=None) -> tuple[MultiTaskActorCritic, list[UpdateStats]]:
    """Train one shared network on all configured tasks and return it with per-update statistics."""
    torch.manual_seed(config.seed)
    np.random.seed(config.seed)
    action_spaces = {task: make(task, size=config.size).n_actions for task in config.tasks}
    model = MultiTaskActorCritic(action_spaces, config.size)
    optimizer = torch.optim.Adam(model.parameters(), lr=config.learning_rate, eps=1e-5)
    rollouts = {task: TaskRollout(task, config, seed=config.seed * 1000 + 100 * i) for i, task in enumerate(config.tasks)}
    history: list[UpdateStats] = []
    started = time.perf_counter()
    batch = config.num_envs * config.rollout_steps
    minibatch = batch // config.minibatches

    for update in range(1, config.updates + 1):
        # Linear learning-rate annealing, standard for PPO.
        for group in optimizer.param_groups:
            group["lr"] = config.learning_rate * (1 - (update - 1) / config.updates)
        progress = (update - 1) / max(config.updates - 1, 1)
        entropy_coef = config.entropy_coef + progress * (config.entropy_coef_final - config.entropy_coef)
        model.eval()
        data = {}
        for task, rollout in rollouts.items():
            raw = rollout.collect(model, config.rollout_steps, config.gamma, config.bootstrap_truncation)
            advantages, returns = gae(raw["rewards"], raw["values"], raw["dones"], raw["last_value"], config.gamma, config.gae_lambda)
            data[task] = {
                "obs": torch.from_numpy(raw["obs"].reshape(batch, *raw["obs"].shape[2:])),
                "actions": torch.from_numpy(raw["actions"].reshape(batch)),
                "log_probs": torch.from_numpy(raw["log_probs"].reshape(batch)),
                "advantages": torch.from_numpy(advantages.reshape(batch)),
                "returns": torch.from_numpy(returns.reshape(batch)),
            }
        model.train()
        losses = {task: {"policy": 0.0, "value": 0.0, "entropy": 0.0, "clip_fraction": 0.0} for task in config.tasks}
        for _ in range(config.epochs):
            orders = {task: torch.randperm(batch) for task in config.tasks}
            for start in range(0, batch, minibatch):
                total = 0.0
                for task in config.tasks:
                    idx = orders[task][start:start + minibatch]
                    d = data[task]
                    logits, values = model(d["obs"][idx], task)
                    dist = Categorical(logits=logits)
                    new_log_prob = dist.log_prob(d["actions"][idx])
                    adv = d["advantages"][idx]
                    adv = (adv - adv.mean()) / (adv.std() + 1e-8)
                    policy_loss = clipped_policy_loss(new_log_prob, d["log_probs"][idx], adv, config.clip)
                    value_loss = 0.5 * (values - d["returns"][idx]).pow(2).mean()
                    entropy = dist.entropy().mean()
                    total = total + policy_loss + config.value_coef * value_loss - entropy_coef * entropy
                    with torch.no_grad():
                        clipped = ((new_log_prob - d["log_probs"][idx]).exp() - 1).abs() > config.clip
                    scale = 1 / (config.epochs * config.minibatches)
                    stats = losses[task]
                    stats["policy"] += policy_loss.item() * scale
                    stats["value"] += value_loss.item() * scale
                    stats["entropy"] += entropy.item() * scale
                    stats["clip_fraction"] += clipped.float().mean().item() * scale
                optimizer.zero_grad()
                total.backward()
                nn.utils.clip_grad_norm_(model.parameters(), config.max_grad_norm)
                optimizer.step()

        per_task = {}
        for task, rollout in rollouts.items():
            episodes = rollout.drain_episodes()
            per_task[task] = {
                **{key: round(value, 5) for key, value in losses[task].items()},
                "episodes": len(episodes),
                "mean_return": round(float(np.mean([r for r, _ in episodes])), 4) if episodes else None,
                "success_rate": round(float(np.mean([s for _, s in episodes])), 4) if episodes else None,
            }
        stats = UpdateStats(update, update * batch * len(config.tasks), round(time.perf_counter() - started, 2), per_task)
        history.append(stats)
        if on_update:
            on_update(stats)
    return model, history


def config_dict(config: PPOConfig) -> dict:
    data = asdict(config)
    data["tasks"] = list(config.tasks)
    return data
